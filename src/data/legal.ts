export type LegalDocId = 'terms' | 'privacy';

/** Блок документа: абзац текста или маркированный список. */
export type LegalBlock =
  | { type: 'text'; text: string }
  | { type: 'list'; items: readonly string[] };

export interface LegalSection {
  id: string;
  heading: string;
  blocks: readonly LegalBlock[];
}

export interface LegalDoc {
  id: LegalDocId;
  /** Маршрут страницы */
  href: string;
  /** Заголовок в подвале и в навигации */
  navLabel: string;
  title: string;
  lead: string;
  sections: readonly LegalSection[];
  /** Заголовок блока с реквизитами оператора (строится из LEGAL_OPERATOR) */
  operatorHeading: string;
}

