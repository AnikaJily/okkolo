/**
 * Юридические тексты сайта «Окколо»: условия покупки и возврата и политика
 * обработки персональных данных.
 *
 * Зачем и где это размещается (ресёрч «где указывать»):
 *  - Политика обработки ПД — ст. 18.1 ч. 2 152-ФЗ: оператор, собирающий данные
 *    через сайт (а у нас формы записи и оформления заказа), обязан опубликовать
 *    документ о политике в свободном доступе на сайте. Согласие субъекта (чекбокс
 *    в формах) — уже есть; политика — то, на что этот чекбокс должен ссылаться.
 *  - Условия покупки и возврата — ст. 26.1 ЗоЗПП («дистанционный способ продажи»)
 *    и Правила продажи товаров ПП РФ № 2463: до заключения договора продавец
 *    обязан довести до покупателя порядок оплаты, доставки и — отдельно —
 *    порядок и сроки возврата товара. Если памятка о возврате не вручена в
 *    письменной форме, срок возврата растягивается с 7 дней до 3 месяцев — эта
 *    страница и есть письменная форма.
 *
 * Размещение в UI: отдельные страницы /terms и /privacy, ссылки в подвале и
 * рядом с каждым чекбоксом согласия (корзина, запись на событие, запись в
 * мастерскую). HTML-страницы выбраны сознательно вместо PDF: текст доступен
 * скринридерам и масштабируется (PDF «Положение о ПД» в /reports — отдельный
 * официальный документ фонда, эта страница — его человекочитаемое изложение).
 *
 * РЕКВИЗИТЫ ОПЕРАТОРА пока не подтверждены заказчицей. По конвенции site.ts
 * (CONTACT_PHONE) и reports.ts держим их пустыми; UI на пустых значениях
 * показывает отсылку к разделу «Отчёты», где реквизиты фонда публикуются
 * официально. Когда заказчица подтвердит — заполнить legalName / inn / ogrn /
 * registeredAddress ниже, остальной текст подстроится автоматически.
 */

